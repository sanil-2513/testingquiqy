import os
from threading import Lock
from sqlalchemy import create_engine, text
from sqlalchemy.engine import make_url

class DatabaseManager:
    """Singleton database gateway. SQLite locally; PostgreSQL when DATABASE_URL is set."""
    _instance = None
    _lock = Lock()

    def __new__(cls, database_url=None):
        with cls._lock:
            if cls._instance is None:
                cls._instance = super().__new__(cls)
                cls._instance._initialized = False
        return cls._instance

    def __init__(self, database_url=None):
        if self._initialized: return
        url = database_url or os.getenv("DATABASE_URL") or "sqlite:///goodbite.db"
        if url.startswith("postgres://"): url = url.replace("postgres://", "postgresql+psycopg://", 1)
        elif url.startswith("postgresql://"): url = url.replace("postgresql://", "postgresql+psycopg://", 1)
        self.engine = create_engine(url, pool_pre_ping=True, future=True)
        self._schema_initialized = False
        self._initialized = True

    def initialize(self):
        if self._schema_initialized:
            return
        statements = [
            """CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                name VARCHAR(120) NOT NULL, email VARCHAR(255) NOT NULL UNIQUE,
                password_hash TEXT NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'customer')""",
            """CREATE TABLE IF NOT EXISTS menu_items (
                id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                name VARCHAR(120) NOT NULL, description TEXT NOT NULL,
                category VARCHAR(30) NOT NULL, price NUMERIC(10,2) NOT NULL)""",
            """CREATE TABLE IF NOT EXISTS orders (
                id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                user_id INTEGER, customer VARCHAR(120) NOT NULL, email VARCHAR(255),
                address TEXT NOT NULL, items_json TEXT NOT NULL, subtotal NUMERIC(10,2) NOT NULL,
                discount NUMERIC(10,2) NOT NULL, total NUMERIC(10,2) NOT NULL,
                payment_method VARCHAR(30) NOT NULL, payment_reference VARCHAR(100) NOT NULL,
                status VARCHAR(40) NOT NULL, created_at VARCHAR(40) NOT NULL)"""
        ]
        # SQLite uses AUTOINCREMENT rather than SQL-standard identity syntax.
        if self.engine.dialect.name == "sqlite":
            statements = [s.replace("INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY",
                                     "INTEGER PRIMARY KEY AUTOINCREMENT") for s in statements]
        with self.engine.begin() as con:
            for sql in statements: con.execute(text(sql))
            count = con.execute(text("SELECT COUNT(*) FROM menu_items")).scalar_one()
            if count == 0:
                from .auth_menu.menu_factory import MenuItemFactory
                seed = [
                    ("main","Classic Burger","Grilled patty, lettuce and house sauce",129),
                    ("main","Margherita Pizza","Mozzarella, tomato and basil",249),
                    ("main","Veg Sandwich","Fresh vegetables and cheese",119),
                    ("side","Golden Fries","Crispy seasoned potato fries",89),
                    ("side","Onion Rings","Crunchy golden onion rings",79),
                    ("drink","Cold Coffee","Chilled creamy coffee",99),
                    ("drink","Lemon Soda","Fresh sparkling lemon drink",69),
                    ("dessert","Chocolate Brownie","Warm chocolate brownie",109)]
                for category,name,description,price in seed:
                    item = MenuItemFactory.create(category,name,description,price)
                    con.execute(text("INSERT INTO menu_items(name,description,category,price) VALUES(:n,:d,:c,:p)"),
                                {"n":item.name,"d":item.description,"c":item.category,"p":item.price})
            admin = con.execute(text("SELECT id FROM users WHERE email=:email"),
                                {"email":"admin@goodbite.local"}).first()
            if not admin:
                from werkzeug.security import generate_password_hash
                con.execute(text("INSERT INTO users(name,email,password_hash,role) VALUES(:n,:e,:p,'admin')"),
                            {"n":"Restaurant Admin","e":"admin@goodbite.local",
                             "p":generate_password_hash(os.getenv("ADMIN_PASSWORD","Admin123!"))})
        self._schema_initialized = True

    def get_user_by_email(self,email):
        with self.engine.connect() as con:
            row=con.execute(text("SELECT * FROM users WHERE email=:e"),{"e":email}).mappings().first()
            return dict(row) if row else None
    def get_user_by_id(self,user_id):
        with self.engine.connect() as con:
            row=con.execute(text("SELECT id,name,email,role FROM users WHERE id=:id"),{"id":user_id}).mappings().first()
            return dict(row) if row else None
    def create_user(self,name,email,password_hash):
        with self.engine.begin() as con:
            result=con.execute(text("INSERT INTO users(name,email,password_hash,role) VALUES(:n,:e,:p,'customer')"),
                               {"n":name,"e":email,"p":password_hash})
            return result.lastrowid
    def get_menu(self):
        with self.engine.connect() as con:
            return [dict(r) for r in con.execute(text("SELECT * FROM menu_items ORDER BY category,name")).mappings()]
    def get_menu_item(self,item_id):
        with self.engine.connect() as con:
            row=con.execute(text("SELECT * FROM menu_items WHERE id=:id"),{"id":item_id}).mappings().first()
            return dict(row) if row else None
    def insert_menu_item(self,item):
        with self.engine.begin() as con:
            result=con.execute(text("INSERT INTO menu_items(name,description,category,price) VALUES(:n,:d,:c,:p) RETURNING id"),
                               {"n":item.name,"d":item.description,"c":item.category,"p":item.price})
            return result.scalar_one()
    def delete_menu_item(self,item_id):
        with self.engine.begin() as con:
            con.execute(text("DELETE FROM menu_items WHERE id=:id"),{"id":item_id})
